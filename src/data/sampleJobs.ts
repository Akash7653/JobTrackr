// Generate dynamic relative dates around current date
const now = new Date();
const getDateOffset = (offsetDays: number) => {
  const d = new Date(now);
  d.setDate(d.getDate() + offsetDays);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
};

const getDateTimeOffset = (offsetDays: number, hours: number, minutes: number) => {
  const dateStr = getDateOffset(offsetDays);
  const h = String(hours).padStart(2, '0');
  const min = String(minutes).padStart(2, '0');
  return `${dateStr}T${h}:${min}:00`;
};

